class AdminUserCreateSerializer(serializers.ModelSerializer):
    """Admin-side user creation: email + name + an initial password + roles.

    Onboarding is admin-set-password only (no invite email): the raw password is
    chosen/generated by the admin and shown once in the UI, never stored.
    """

    password = serializers.CharField(
        write_only=True,
        style={"input_type": "password"},
        validators=[validate_password],
    )
    roles = serializers.ListField(
        child=serializers.CharField(), required=False, default=list
    )

    class Meta:
        model = User
        fields = ["id", "email", "full_name", "password", "roles"]
        read_only_fields = ["id"]

    def validate_roles(self, value):
        return _validate_role_names(value)

    def create(self, validated_data):
        roles = validated_data.pop("roles", [])
        user = User.objects.create_user(**validated_data)
        if roles:
            user.roles.set(roles)
        return user


class AdminUserUpdateSerializer(serializers.ModelSerializer):
    """Partial admin update: display name, active flag, and/or role set."""

    roles = serializers.ListField(
        child=serializers.CharField(), required=False
    )

    class Meta:
        model = User
        fields = ["full_name", "is_active", "roles"]

    def validate_roles(self, value):
        return _validate_role_names(value)

    def update(self, instance, validated_data):
        roles = validated_data.pop("roles", None)
        for attr, val in validated_data.items():
            setattr(instance, attr, val)
        instance.save()
        if roles is not None:
            instance.roles.set(roles)
        return instance


